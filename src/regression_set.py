    # 那半句实测不成立，已删。** 候选闸是 lexical_admit 与 BM25>0 的 AND，
    # 两半在本回归集上判空的是**同一批 5 条**，把 lexical_admit 换成"全放行"
    # 重跑，absent 三类一个数不动（数与判据见下面那两行 ⚠）。
    # 所以"砍掉 90.6%、5 条判空"说的是**闸自己的行为**，不等于**端到端的独立
