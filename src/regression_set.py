#   ① 是**规模**伪影：max_df = max(3, N//5) 本质是 20% 的比例阈值。14 块语料里
#      一条跨三窗的主题线占 36%，当然超标；真实语料 755 块时同样一条线占 0.7%。
#      实测：N≥30 主题词就过关。
#   ② 是**词频分布**伪影：填充块话题多样但**文风单调**，不含"那晚""以后"这类
#      真实记忆记录里满地都是的口语连接词，于是这些闲词 df 假性偏低（2/200）、
