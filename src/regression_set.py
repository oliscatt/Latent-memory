def _fmt(scores):
    lines = []
    for kind in QUERY_KINDS:
        s = scores.get(kind)
        if not s:
            continue
        if is_empty_kind(kind):
            lines.append(f"  {kind:<14} n={s['n']}  正确空手率 {s['correct_empty']:.2f}")
        else:
            lines.append(f"  {kind:<14} n={s['n']}  Recall@{TOPN} {s['recall']:.2f}  MRR {s['mrr']:.2f}")
    return "\n".join(lines)


